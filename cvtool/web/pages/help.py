def 장고르기(경로: str) -> str:
    """지금 화면에 맞는 장의 열쇠. 가장 길게 맞는 경로를 고른다."""
    고른것, 길이 = "start", 0
    for 열쇠, _제목, 경로들, _본문 in 장들:
        for p in 경로들:
            맞음 = 경로 == p if p == "/" else (경로 == p or 경로.startswith(p + "/")
                                             or 경로.startswith(p + "?"))
            if 맞음 and len(p) > 길이:
                고른것, 길이 = 열쇠, len(p)
    return 고른것


