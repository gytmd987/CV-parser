        "- 전문성_성과: 무엇에 전문성이 있는지·대표 성과.\n"
        "- 연구전문가_역량: 연구자로서의 태도·성품.\n"
        "- 작성자: **이번 후보자 원본** 끝에 적힌 작성자 이름만 순서대로 (직함·'작성자' 같은 말은 빼고). "
        "예시 자료의 이름을 쓰지 마라.\n\n"
        "[출력 형식] 충분히 생각한 뒤, 마지막에 아래 모양 그대로만 써라. 대괄호 표시는 바꾸지 마라.\n"
