def 검사(결: 결과, 학습: dict) -> list[str]:
    """고쳐야 할 것들 (LLM 에게 그대로 보낼 말)."""
    문제 = []
    for 칸, 이름, 글 in (("전문성", "전문성_성과", 결.전문성), ("역량", "연구전문가_역량", 결.역량)):
        if not 글.strip():
            문제.append(f"{이름}이 비었습니다.")
            continue
        한도 = _한줄글자(학습, 칸)
        덩들 = _요약줄들(글, 학습, 칸)
        줄 = sum(len(d) for d in 덩들)
        if len(덩들) > 2:
            문제.append(f"{이름}의 내용(점)이 {len(덩들)}개입니다. 두 개까지만 쓰세요.")
        elif len(덩들) == 2 and 줄 > 2:
            문제.append(f"{이름}의 내용이 두 개인데 칸에서 {줄}줄입니다. 내용이 두 개면 각각 "
                      f"한 줄(공백 포함 {int(한도 * 0.9)}자 안쪽)이어야 합니다. 줄이거나 하나로 합치세요.")
        elif 줄 > 2:
            문제.append(f"{이름}이 칸에서 {줄}줄입니다. 공백 포함 {int(한도 * 2 * 0.85)}자 안쪽으로 줄이세요.")
    칸1, 칸2 = 학습["칸"]["1장_첫열"], 학습["칸"]["1장_둘째열"]
    높이 = fit.표높이(결.항목, 칸1["폭_pt"] / 칸1["크기_pt"], 칸2["폭_pt"] / 칸2["크기_pt"])
    한도 = 학습["분량"]["표높이"]
    if 한도 and 높이 > 한도 * 1.02:
        넘침 = round((높이 / 한도 - 1) * 100)
        긴것 = sorted(range(len(결.항목)), key=lambda i: -len(결.항목[i][1]))[:3]
        문제.append(f"1장 분량을 {넘침}% 넘습니다. 특히 "
                  + ", ".join(f"'{결.항목[i][0]}'" for i in 긴것) + " 을(를) 더 줄이세요.")
    return 문제


def _받기(답: dict, 자료: D.검증자료, 학습: dict) -> 결과:
    의견 = [의견맞추기(str(x).strip(), 학습) for x in (답.get("검증의견") or [])]
    의견 += [""] * (len(자료.항목) - len(의견))
    작성자 = [str(x).strip() for x in (답.get("작성자") or []) if str(x).strip()]
    return 결과(
        자료=자료,
        항목=[(a, 의견[i]) for i, (a, _b) in enumerate(자료.항목)],
        전문성=요약맞추기(str(답.get("전문성_성과") or "").strip(), 학습, "전문성"),
        역량=요약맞추기(str(답.get("연구전문가_역량") or "").strip(), 학습, "역량"),
        작성자=작성자 or D.작성자_찾기(자료.끝글)[:3],
    )


_표시 = re.compile(r"^\s*[\[［【]\s*([^\]］】\n]{1,30}?)\s*[\]］】]\s*[:：]?\s*(.*)$")


def 풀기(글: str, n: int) -> dict | None:
    """[의견1] … [작성자] 로 표시된 글을 나눈다. 의견이 하나도 없으면 None.

    추론 모델은 앞에 생각을 길게 쓰기도 하므로 **마지막에 나온** 표시를 쓴다.
    """
    칸: dict[str, list[str]] = {}
    지금 = None
    for 줄 in (글 or "").splitlines():
        m = _표시.match(줄)
        if m:
            이름 = re.sub(r"\s+", "", m.group(1))
            if re.fullmatch(r"(의견|검증의견)?\d+", 이름):
                지금 = "의견" + re.sub(r"\D", "", 이름)
            elif "전문성" in 이름 or "성과" in 이름:
                지금 = "전문성"
            elif "역량" in 이름:
                지금 = "역량"
            elif "작성자" in 이름:
                지금 = "작성자"
            else:
                지금 = None
                continue
            칸[지금] = [m.group(2)] if m.group(2).strip() else []   # 다시 나오면 새로 (마지막 것)
            continue
        if 지금:
            칸[지금].append(줄)

    def 글(k):
        return "\n".join(x.rstrip() for x in 칸.get(k, [])).strip()

    의견 = [글(f"의견{i + 1}") for i in range(n)]
    if not any(의견):
        return None
    return {
        "검증의견": 의견,
        "전문성_성과": 글("전문성"),
        "연구전문가_역량": 글("역량"),
        "작성자": [x.strip() for x in re.split(r"[/,·\n]+", 글("작성자")) if x.strip()],
    }


def _묻기(client, 메시지: list[dict], n: int) -> tuple[dict, str]:
    """(나눈 답, 원래 글). 글로 받고, 못 나누면 그 글을 JSON 으로 옮기게 한 번 더."""
    글 = client.chat_text(메시지)
    답 = 풀기(글, n)
    if 답 is None:
        답 = client.chat_json(
            메시지 + [{"role": "assistant", "content": 글},
                    {"role": "user", "content": "위에 쓴 내용을 JSON 으로 옮겨라. 내용은 바꾸지 마라."}],
            _스키마(n), schema_name="verify_summary")
    return 답, 글


def 한사람(자료: D.검증자료, 학습: dict, client) -> 결과:
    n = len(자료.항목)
    메시지 = 프롬프트(자료, 학습)
    답, 글 = _묻기(client, 메시지, n)
    결 = _받기(답, 자료, 학습)
    for _ in range(고쳐쓰기):
        문제 = 검사(결, 학습)
        if any(not b for _a, b in 결.항목):
            문제.append("비어 있는 검증 의견이 있습니다. 모든 [의견] 칸을 채우세요.")
        if not 문제:
            break
        메시지 = 메시지 + [
            {"role": "assistant", "content": 글},
            {"role": "user", "content": "다음을 고쳐 같은 [표시] 형식으로 처음부터 다시 써라. "
             "나머지는 그대로 둔다.\n- " + "\n- ".join(문제)},
        ]
        답, 글 = _묻기(client, 메시지, n)
        결 = _받기(답, 자료, 학습)
    결.원답 = 글[-4000:]

    # 마지막 안전장치 — 요약 칸은 두 줄을 절대 넘지 않게
    for 칸, 속성, 이름 in (("전문성", "전문성", "전문성/성과"), ("역량", "역량", "연구전문가 역량")):
        덩들 = fit.항목_나누기(getattr(결, 속성))
        if sum(len(d) for d in _요약줄들(getattr(결, 속성), 학습, 칸)) <= 2 and len(덩들) <= 2:
            continue
        머리, 들임 = 요약점(학습)
        em = _한줄(학습, 칸)
        if len(덩들) >= 2:            # 점 두 개 → 각각 한 줄
            덩들 = [fit.자르기(d, em, 1, 머리, 들임) for d in 덩들[:2]]
        else:
            덩들 = [fit.자르기(덩들[0], em, 2, 머리, 들임)]
        setattr(결, 속성, 요약맞추기("\n".join(머리 + d for d in 덩들 if d), 학습, 칸))
        결.경고.append(f"{이름}이 길어 두 줄에 맞춰 뒤를 잘랐습니다 — 확인해 주세요.")
    남은 = [m for m in 검사(결, 학습) if "1장 분량" in m]
    if 남은:
        결.경고.append(남은[0].split(" 특히")[0] + " — 워드에서 한 쪽을 넘는지 확인해 주세요.")
    if len(결.작성자) != 3:
        결.경고.append(f"작성자를 {len(결.작성자)}명 찾았습니다 ({', '.join(결.작성자) or '없음'}).")
    if any(not b for _a, b in 결.항목):
        결.경고.append("비어 있는 검증 의견이 있습니다.")
    return 결


