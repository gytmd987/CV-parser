def 한장파일(결과들: list[결과], 틀: bytes) -> bytes:
    return D.한장_만들기(틀, [
        D.한장결과(제목=r.자료.제목, 소속=r.자료.소속, 항목=r.항목, 작성자=r.작성자,
                  작성자문단=r.자료.끝문단)
        for r in 결과들])


def 요약파일(결과들: list[결과], 틀: bytes, 학습: dict) -> bytes:
    열 = 학습["요약"]["열"]
    칸수 = max(len(학습["요약"]["머리"]), max(열.values()) + 1)
    줄들 = []
    for r in 결과들:
        값 = [""] * 칸수
        값[열["후보자"]] = r.자료.이름
        값[열["전문성"]] = r.전문성
        값[열["역량"]] = r.역량
        값[열["결과"]] = "추천"
        줄들.append(값)
    return D.요약_만들기(틀, 줄들)
