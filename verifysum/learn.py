"""1단계 — 예시 세 파일을 보고 '어떻게 줄이고 어떤 말투로 쓰는지' 를 정리한다.

얻는 것:
  - 틀       : 예시 결과 파일 두 개를 그대로 보관 (결과를 만들 때 모양을 복사한다)
  - 칸 모양  : 1장 표 두 열의 너비, 요약표 칸 너비·글자 크기 → 몇 줄이 되는지 셀 때
  - 분량     : 예시 1장 표의 높이 (= 한 쪽에 들어간 양) · 항목별 글자 수
  - 지침     : LLM 이 예시 원본과 결과를 나란히 보고 쓴 작성 지침 (화면에서 고칠 수 있다)
  - 예시 글  : 원본 · 1장 · 요약 줄 — 결과를 만들 때 프롬프트에 그대로 보여 준다
"""

from __future__ import annotations

import json
import time
from dataclasses import asdict
from pathlib import Path

from . import docxio as D
from . import fit

학습파일 = "학습.json"
틀_1장 = "틀_1장.docx"
틀_요약 = "틀_요약.docx"


def _열찾기(머리: list[str]) -> dict[str, int]:
    열 = {"후보자": 0, "전문성": 1, "역량": 2, "결과": 3}
    for i, 이름 in enumerate(머리):
        n = 이름.replace(" ", "")
        if "역량" in n:                    # '연구전문가 역량' 에도 '전문' 이 들어 있다
            열["역량"] = i
        elif "전문" in n or "성과" in n:
            열["전문성"] = i
        elif "결과" in n:
            열["결과"] = i
        elif any(k in n for k in ("후보", "성명", "이름")):
            열["후보자"] = i
    return 열


def 분석(원본: bytes, 한장: bytes, 요약: bytes) -> dict:
    """LLM 없이 알 수 있는 것 전부. 지침은 `지침_만들기` 가 채운다."""
    예원 = D.검증자료_읽기(원본, "예시 원본")
    한장들 = D.항목들(D._열기(한장))
    if not 한장들:
        raise D.형식오류("1장 예시 파일에서 표를 찾지 못했습니다.")
    예한 = next((p for p in 한장들 if p.이름 == 예원.이름), 한장들[0])
    요약제목, 머리, 요약줄 = D.요약표_읽기(요약)
    열 = _열찾기(머리)

    # 칸 모양
    한장문서 = D._열기(한장)
    표 = 한장문서.tables[0]._tbl
    첫열 = D.칸모양_읽기(표, 0, 한장문서)
    둘째열 = D.칸모양_읽기(표, 1, 한장문서)
    요약문서 = D._열기(요약)
    요약표 = 요약문서.tables[0]._tbl
    전문칸 = D.칸모양_읽기(요약표, 열["전문성"], 요약문서, 기본폭_cm=7.0, 기본크기=11.0)
    역량칸 = D.칸모양_읽기(요약표, 열["역량"], 요약문서, 기본폭_cm=7.0, 기본크기=11.0)

    예산 = fit.표높이(예한.항목, 첫열.한줄_em, 둘째열.한줄_em)
    return {
        "만든때": time.strftime("%Y-%m-%d %H:%M"),
        "원본": asdict(예원),
        "한장": asdict(예한),
        "요약": {"제목": 요약제목, "머리": 머리, "줄들": 요약줄, "열": 열},
        "칸": {
            "1장_첫열": asdict(첫열), "1장_둘째열": asdict(둘째열),
            "전문성": asdict(전문칸), "역량": asdict(역량칸),
        },
        "분량": {
            "표높이": 예산,
            "원본글자": [len(b) for _a, b in 예원.항목],
            "1장글자": [len(b) for _a, b in 예한.항목],
        },
        "작성자예": D.작성자_찾기(예원.끝글),
        "지침": "",
    }


def _표글(항목: list) -> str:
    return "\n".join(f"[{a}]\n{b}" for a, b in 항목)


def 예시글(학습: dict) -> str:
    """결과를 만들 때와 지침을 만들 때 같이 보여 주는 예시 묶음."""
    요 = 학습["요약"]
    열 = 요["열"]
    줄 = "\n".join(
        f"- 후보자: {r[열['후보자']] if len(r) > 열['후보자'] else ''}"
        f"\n  전문성/성과: {r[열['전문성']] if len(r) > 열['전문성'] else ''}"
        f"\n  연구전문가 역량: {r[열['역량']] if len(r) > 열['역량'] else ''}"
        for r in 요["줄들"][:6])
    return (
        f"<예시 원본 검증 자료 — {학습['원본']['제목']}>\n{_표글(학습['원본']['항목'])}\n\n"
        f"<예시 1장 결과 — 같은 사람을 줄인 것>\n{_표글(학습['한장']['항목'])}\n\n"
        f"<예시 요약표 줄>\n{줄}"
    )


def 지침_만들기(학습: dict, client) -> str:
    """LLM 이 예시를 나란히 보고 작성 지침을 쓴다. 실패하면 숫자로만 만든 기본 지침."""
    전문 = fit.줄에_맞는_글자수(학습["칸"]["전문성"]["폭_pt"] / 학습["칸"]["전문성"]["크기_pt"])
    지시 = (
        "너는 연구자 검증 자료를 정리하는 담당자다. 아래 예시는 여러 사람이 쓴 "
        "원본 검증 자료와, 그것을 하나의 문체로 다듬어 줄인 결과다.\n"
        "앞으로 다른 후보자 30~40명의 자료를 같은 방식으로 정리할 수 있도록 "
        "**작성 지침**을 써라.\n\n"
        "다음 제목으로 짧은 글머리표 목록을 써라 (전체 25줄 이내, 한국어):\n"
        "[문체] 문장 끝맺음(예: ~함 / ~임 / 명사형), 존칭 여부, 문장 길이\n"
        "[1장으로 줄이는 법] 무엇을 남기고 무엇을 빼는지, 수치·기관명·논문 처리, 줄 나눔 방식\n"
        f"[전문성/성과 칸] 어떤 내용을 어떤 순서로 쓰는지 (두 줄, 약 {전문}자 이내)\n"
        "[연구전문가 역량 칸] 연구자 태도·성품을 어떻게 표현하는지 (두 줄 이내)\n"
        "[주의] 지어내지 말 것 등\n"
        "예시에서 실제로 보이는 특징만 써라. 지침 말고 다른 말은 쓰지 마라."
    )
    try:
        return client.chat_text([
            {"role": "system", "content": 지시},
            {"role": "user", "content": 예시글(학습)},
        ]).strip()
    except Exception as exc:  # noqa: BLE001 - 지침이 없어도 다음 단계는 할 수 있게
        return 기본지침(학습) + f"\n\n(자동 지침을 만들지 못했습니다: {exc})"


def 기본지침(학습: dict) -> str:
    원 = sum(학습["분량"]["원본글자"]) or 1
    한 = sum(학습["분량"]["1장글자"])
    return (
        "[문체]\n- 예시 1장 결과와 같은 문장 끝맺음으로 통일한다.\n"
        f"[1장으로 줄이는 법]\n- 원문 분량의 약 {round(한 / 원 * 100)}% 로 줄인다.\n"
        "- 수치·기관명·대표 성과는 남기고 수식어·중복은 뺀다.\n"
        "[전문성/성과 칸]\n- 전문 분야와 대표 성과를 한 덩어리로 짧게.\n"
        "[연구전문가 역량 칸]\n- 연구 태도·협업·성품을 짧게.\n"
        "[주의]\n- 원문에 없는 내용은 쓰지 않는다."
    )


# --- 저장 ------------------------------------------------------------------------
def 저장(폴더: Path, 학습: dict, 한장: bytes | None = None, 요약: bytes | None = None) -> None:
    폴더.mkdir(parents=True, exist_ok=True)
    (폴더 / 학습파일).write_text(json.dumps(학습, ensure_ascii=False, indent=1), encoding="utf-8")
    if 한장 is not None:
        (폴더 / 틀_1장).write_bytes(한장)
    if 요약 is not None:
        (폴더 / 틀_요약).write_bytes(요약)


def 불러오기(폴더: Path) -> dict | None:
    p = 폴더 / 학습파일
    if not (p.exists() and (폴더 / 틀_1장).exists() and (폴더 / 틀_요약).exists()):
        return None
    return json.loads(p.read_text(encoding="utf-8"))
