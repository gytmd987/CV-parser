def 다시분석(폴더: Path, client) -> dict:
    """이미 올린 예시 세 파일로 처음부터 다시 분석한다 (파일을 다시 올리지 않아도 된다)."""
    옛 = 불러오기(폴더)
    if not 옛:
        raise D.형식오류("먼저 예시 세 파일을 올려 분석해 주세요.")
    if (폴더 / 예시_원본).exists():
        원본 = (폴더 / 예시_원본).read_bytes()
    else:                         # 예전 분석은 원본 파일을 안 남겼다 — 읽어 둔 내용으로
        o = 옛["원본"]
        원본 = D.검증자료(제목=o["제목"], 소속=o["소속"], 항목=[tuple(x) for x in o["항목"]],
                       끝글=o.get("끝글", ""), 파일명=o.get("파일명", ""), 끝문단=o.get("끝문단") or [])
    학습 = 분석(원본, (폴더 / 틀_1장).read_bytes(), (폴더 / 틀_요약).read_bytes())
    학습["지침"] = 지침_만들기(학습, client)
    저장(폴더, 학습)
    return 학습


def 저장(폴더: Path, 학습: dict, 한장: bytes | None = None, 요약: bytes | None = None,
       원본: bytes | None = None) -> None:
    폴더.mkdir(parents=True, exist_ok=True)
    if 원본 is not None:
        (폴더 / 예시_원본).write_bytes(원본)
    (폴더 / 학습파일).write_text(json.dumps(학습, ensure_ascii=False, indent=1), encoding="utf-8")
    if 한장 is not None:
        (폴더 / 틀_1장).write_bytes(한장)
    if 요약 is not None:
        (폴더 / 틀_요약).write_bytes(요약)


def 불러오기(폴더: Path) -> dict | None:
    p = 폴더 / 학습파일
    if not (p.exists() and (폴더 / 틀_1장).exists() and (폴더 / 틀_요약).exists()):
        return None
    return json.loads(p.read_text(encoding="utf-8"))
