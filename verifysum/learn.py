틀_요약 = "틀_요약.docx"
예시_원본 = "예시_원본.docx"


def _열찾기(머리: list[str]) -> dict[str, int]:
    열 = {"후보자": 0, "전문성": 1, "역량": 2, "결과": 3}
    for i, 이름 in enumerate(머리):
        n = 이름.replace(" ", "")
        if "역량" in n:                    # '연구전문가 역량' 에도 '전문' 이 들어 있다
            열["역량"] = i
        elif "전문" in n or "성과" in n:
            열["전문성"] = i
        elif "결과" in n:
            열["결과"] = i
        elif any(k in n for k in ("후보", "성명", "이름")):
            열["후보자"] = i
    return 열


def 분석(원본: bytes | D.검증자료, 한장: bytes, 요약: bytes) -> dict:
    """LLM 없이 알 수 있는 것 전부. 지침은 `지침_만들기` 가 채운다.

    원본은 파일 대신 읽어 둔 `검증자료` 로 줘도 된다 (예전 분석에서 원본 파일을 안 남겼을 때)."""
    예원 = 원본 if isinstance(원본, D.검증자료) else D.검증자료_읽기(원본, "예시 원본")
    한장들 = D.항목들(D._열기(한장))
    if not 한장들:
        raise D.형식오류("1장 예시 파일에서 표를 찾지 못했습니다.")
    예한 = next((p for p in 한장들 if p.이름 == 예원.이름), 한장들[0])
    요약제목, 머리, 요약줄 = D.요약표_읽기(요약)
    열 = _열찾기(머리)

    # 칸 모양
    한장문서 = D._열기(한장)
    표 = 한장문서.tables[0]._tbl
    첫열 = D.칸모양_읽기(표, 0, 한장문서)
    둘째열 = D.칸모양_읽기(표, 1, 한장문서)
    요약문서 = D._열기(요약)
    요약표 = 요약문서.tables[0]._tbl
    전문칸 = D.칸모양_읽기(요약표, 열["전문성"], 요약문서, 기본폭_cm=7.0, 기본크기=11.0)
    역량칸 = D.칸모양_읽기(요약표, 열["역량"], 요약문서, 기본폭_cm=7.0, 기본크기=11.0)

    예산 = fit.표높이(예한.항목, 첫열.한줄_em, 둘째열.한줄_em)
    return {
        "만든때": time.strftime("%Y-%m-%d %H:%M"),
        "원본": asdict(예원),
        "한장": asdict(예한),
        "요약": {"제목": 요약제목, "머리": 머리, "줄들": 요약줄, "열": 열},
        "칸": {
            "1장_첫열": asdict(첫열), "1장_둘째열": asdict(둘째열),
            "전문성": asdict(전문칸), "역량": asdict(역량칸),
        },
        "분량": {
            "표높이": 예산,
            "원본글자": [len(b) for _a, b in 예원.항목],
            "1장글자": [len(b) for _a, b in 예한.항목],
        },
        "작성자예": D.작성자_찾기(예원.끝글),
        "지침": "",
    }


def _표글(항목: list) -> str:
    return "\n".join(f"[{a}]\n{b}" for a, b in 항목)


def 예시글(학습: dict) -> str:
    """결과를 만들 때와 지침을 만들 때 같이 보여 주는 예시 묶음."""
    요 = 학습["요약"]
    열 = 요["열"]
    줄 = "\n".join(
        f"- 후보자: {r[열['후보자']] if len(r) > 열['후보자'] else ''}"
        f"\n  전문성/성과: {r[열['전문성']] if len(r) > 열['전문성'] else ''}"
        f"\n  연구전문가 역량: {r[열['역량']] if len(r) > 열['역량'] else ''}"
        for r in 요["줄들"][:6])
    return (
        f"<예시 원본 검증 자료 — {학습['원본']['제목']}>\n{_표글(학습['원본']['항목'])}\n\n"
        f"<예시 1장 결과 — 같은 사람을 줄인 것>\n{_표글(학습['한장']['항목'])}\n\n"
        f"<예시 요약표 줄>\n{줄}"
    )


def 예시이름(학습: dict) -> list[str]:
    """예시 파일에 나온 사람 이름 (후보자 · 작성자) — 지침에 남지 않게 지운다."""
    이름 = list(학습.get("작성자예") or [])
    for 제목 in (학습["원본"].get("제목", ""), 학습["한장"].get("제목", "")):
        이름.append(D.이름_직책(제목)[0])
    열 = 학습["요약"]["열"]["후보자"]
    이름 += [r[열] for r in 학습["요약"]["줄들"] if len(r) > 열]
    return sorted({x.strip() for x in 이름 if len(x.strip()) >= 2}, key=len, reverse=True)


def 이름지우기(글: str, 학습: dict) -> str:
    """지침 속 예시 사람 이름을 OOO 로. 다른 후보자 결과에 예시 이름이 섞이지 않게."""
    for x in 예시이름(학습):
        글 = 글.replace(x, "OOO")
    return 글


def 형식지침() -> str:
    """칸 글 모양 — 예시 문서의 정해진 형식. 지침 끝에 늘 붙고, 결과를 만들 때 규칙으로도 간다."""
    return (
        "[형식 — 정해진 것]\n"
        "- 1장 검증 의견 칸: 구분되는 내용마다 새 줄에 '- ' (줄표+띄어쓰기) 로 시작한다. "
        "내용이 하나여도 '- ' 로 시작한다.\n"
        "- 1장: '- ' 없이 이어지는 줄은 띄어쓰기 두 칸으로 시작해 글자 시작 위치를 맞춘다. "
        "내용 사이는 줄 간격을 조금 벌린다. 칸 높이는 내용에 맞춘다. (줄 맞춤·간격은 프로그램이 한다)\n"
        "- 요약표 두 칸: 내용 구분은 작은 점 '·'. 점은 줄 맨 앞에만 오고, 문장 중간에서 점으로 "
        "내용을 나누지 않는다. 칸에 두 줄이므로 점은 두 개까지 — 두 개면 각각 한 줄, 하나면 두 줄까지.\n"
        "- 요약: 점 없이 이어지는 줄은 띄어쓰기로 글자 시작 위치를 맞춘다. (프로그램이 한다)"
    )


def 지침_만들기(학습: dict, client) -> str:
    """LLM 이 예시를 나란히 보고 작성 지침을 쓴다. 실패하면 숫자로만 만든 기본 지침."""
    전문 = fit.줄에_맞는_글자수(학습["칸"]["전문성"]["폭_pt"] / 학습["칸"]["전문성"]["크기_pt"])
    원 = 학습["분량"]["원본글자"]
    한 = 학습["분량"]["1장글자"]
    비율 = round(sum(한) / max(1, sum(원)) * 100)
    항목명 = [a for a, _b in 학습["원본"]["항목"]]
    지시 = (
        "너는 연구자 검증 자료를 정리하는 담당자다. 아래 예시는 여러 사람이 쓴 "
        "원본 검증 자료와, 그것을 하나의 문체로 다듬어 줄인 1장 결과·요약표다.\n"
        "앞으로 다른 후보자 30~40명의 자료를 같은 방식으로 정리할 수 있도록 **작성 지침**을 써라.\n"
        "이 지침은 다음 작업 때 예시 원문·결과와 **함께** LLM 에 넘어간다. 그러니 예시를 다시 "
        "옮겨 적지 말고, 예시를 비교해서 읽어 낸 **규칙**을 구체적으로 써라.\n\n"
        "아래 제목마다 글머리표 3~6줄 (한국어):\n"
        "[문체] 문장 끝맺음(예시의 실제 표현 인용, 예: '~함', '~임', 명사형), 존칭·주어 생략 여부, "
        "문장 길이, 즐겨 쓰는 표현과 쓰지 않는 표현\n"
        f"[1장으로 줄이는 법] 원문 대비 분량(예시는 약 {비율}%), 남기는 정보(수치·기관명·논문·수상 등), "
        "빼는 정보, 한 칸 안 줄 나눔·글머리 기호\n"
        f"[항목별 요령] 항목마다 한 줄씩 — 무엇을 중심으로 남기는지. 항목: {' / '.join(항목명)}\n"
        f"[전문성/성과 칸] 쓰는 순서와 문장 구조 (칸에서 두 줄, 공백 포함 약 {전문}자 이내). 예시 요약이 "
        "짧은 만큼 '있어 보이게' 쓰는 방법 — 여러 내용을 담는 압축된 단어, '~ 전문가' 같은 강조, "
        "무게감 있는 성과 고르기 — 을 예시 표현을 인용해 구체적으로\n"
        "[연구전문가 역량 칸] 연구자 태도·성품을 쓰는 순서와 표현 (두 줄 이내), 예시의 강조 표현 인용\n"
        "[바꿔 쓰기 예] 예시에서 실제로 대응되는 '원문 문장 → 결과 문장' 3~5쌍\n"
        "[주의] 지어내지 말 것, 평가를 부풀리지 말 것 등\n"
        "칸 글의 글머리 기호·들여쓰기 형식은 아래처럼 정해져 있으니 따로 쓰지 말고, "
        "이와 어긋나는 말도 쓰지 마라:\n" + 형식지침() + "\n"
        "사람 이름(후보자·작성자)은 지침에 쓰지 말고 'OOO' 로 써라 — 이 지침은 다른 사람 자료에 쓰인다.\n"
        "예시에서 실제로 보이는 특징만 써라. 지침 말고 다른 말은 쓰지 마라."
    )
    분량표 = "\n".join(f"- {a}: 원문 {원[i] if i < len(원) else '?'}자 → 1장 {한[i] if i < len(한) else '?'}자"
                    for i, a in enumerate(항목명))
    try:
        글 = client.chat_text([
            {"role": "system", "content": 지시},
            {"role": "user", "content": 예시글(학습) + f"\n\n<항목별 분량>\n{분량표}"},
        ]).strip()
        return 이름지우기(글, 학습) + "\n\n" + 형식지침()
    except Exception as exc:  # noqa: BLE001 - 지침이 없어도 다음 단계는 할 수 있게
        return 기본지침(학습) + f"\n\n(자동 지침을 만들지 못했습니다: {exc})"


def 기본지침(학습: dict) -> str:
    원 = sum(학습["분량"]["원본글자"]) or 1
    한 = sum(학습["분량"]["1장글자"])
    return (
        "[문체]\n- 예시 1장 결과와 같은 문장 끝맺음으로 통일한다.\n"
        f"[1장으로 줄이는 법]\n- 원문 분량의 약 {round(한 / 원 * 100)}% 로 줄인다.\n"
        "- 수치·기관명·대표 성과는 남기고 수식어·중복은 뺀다.\n"
        "[전문성/성과 칸]\n- 전문 분야와 대표 성과를 한 덩어리로 짧게, 그러나 있어 보이게.\n"
        "- 여러 내용을 담는 압축된 단어를 쓰고, 전문성은 '~ 전문가' 처럼 강조한다.\n"
        "[연구전문가 역량 칸]\n- 연구 태도·협업·성품을 짧게, 예시처럼 강조해서.\n"
        "[주의]\n- 원문에 없는 내용은 쓰지 않는다.\n\n" + 형식지침()
    )


