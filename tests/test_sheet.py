"""시트 칸 계산기 — 칸 주소를 값으로 바꿔 주는 층.

새 계산기를 만들지 않았다. `expr.py` 가 이름을 값 묶음에서 찾는 성질을 그대로
쓰고, 없던 것(범위·집계 섞어쓰기·순환 참조)만 여기서 채운다.
"""

from __future__ import annotations

import pytest

from cvtool import formula as F
from cvtool import sheet as S


@pytest.fixture
def rows():
    return F.Rows(
        지원자=[{"부서": "소재분석", "저널_수": "2"},
              {"부서": "소재분석", "저널_수": "4"},
              {"부서": "공정", "저널_수": "0"},
              {"부서": "공정", "저널_수": "6"}],
        채용=[],
    )


# --- 주소 ------------------------------------------------------------------
@pytest.mark.parametrize("r,c,글", [(0, 0, "A1"), (0, 25, "Z1"), (0, 26, "AA1"),
                                   (9, 1, "B10"), (99, 25, "Z100")])
def test_주소와_자리가_서로의_반대다(r, c, 글):
    assert S.주소(r, c) == 글
    assert S.자리(글) == (r, c)


def test_주소가_아니면_거부한다():
    for 못쓰는값 in ("", "1A", "A", "가1", "A0.5"):
        with pytest.raises(ValueError):
            S.자리(못쓰는값)


# --- 칸 참조 ---------------------------------------------------------------
def test_옆_칸_값을_읽는다(rows):
    칸 = {"A1": {"글": "30"}, "A2": {"글": "120"}, "B1": {"글": "=A1/A2*100"}}
    값, 오류 = S.값들(칸, rows)
    assert 값["B1"] == "25"
    assert 오류 == []


def test_수식이_아닌_칸은_글자_그대로(rows):
    값, _ = S.값들({"A1": {"글": "분기 보고"}, "A2": {"글": ""}}, rows)
    assert 값["A1"] == "분기 보고"
    assert 값["A2"] == ""


def test_빈_칸을_가리켜도_안_터진다(rows):
    """아직 안 적은 칸을 가리키는 일은 늘 있다. 0 으로 본다."""
    값, 오류 = S.값들({"A1": {"글": "=B9+1"}}, rows)
    assert 값["A1"] == "1"
    assert 오류 == []


# --- 범위 ------------------------------------------------------------------
def test_범위를_펼친다():
    assert S.범위펼치기("=SUM(A1:A3)") == "=SUM(A1,A2,A3)"
    assert S.범위펼치기("=SUM(A1:B2)") == "=SUM(A1,B1,A2,B2)"


def test_따옴표_안의_범위는_안_펼친다():
    """글자는 글자다. `="A1:A3 을 더함"` 이 쉼표 범벅이 되면 안 된다."""
    assert S.범위펼치기('="A1:A3 을 더함"') == '="A1:A3 을 더함"'
    assert S.범위펼치기('="A1:A2"&SUM(A1:A2)') == '="A1:A2"&SUM(A1,A2)'


def test_범위로_더한다(rows):
    칸 = {"A1": {"글": "1"}, "A2": {"글": "2"}, "A3": {"글": "3"},
         "B1": {"글": "=SUM(A1:A3)"}}
    값, 오류 = S.값들(칸, rows)
    assert (값["B1"], 오류) == ("6", [])


# --- 집계 섞어 쓰기 ----------------------------------------------------------
def test_집계와_계산을_섞는다(rows):
    """이게 «칸마다 외톨이» 였던 것을 푸는 요점이다."""
    칸 = {"A1": {"글": '=COUNT(지원자, 부서="소재분석") / COUNT(지원자) * 100'}}
    값, 오류 = S.값들(칸, rows)
    assert (값["A1"], 오류) == ("50", [])


def test_집계를_다른_함수_안에_넣는다(rows):
    값, 오류 = S.값들({"A1": {"글": "=ROUND(COUNT(지원자)/3, 1)"}}, rows)
    assert (값["A1"], 오류) == ("1.3", [])


def test_집계_결과를_옆_칸에서_다시_쓴다(rows):
    칸 = {"A1": {"글": '=COUNT(지원자, 부서="소재분석")'},
         "A2": {"글": "=COUNT(지원자)"},
         "A3": {"글": "=A1/A2*100"}}
    값, 오류 = S.값들(칸, rows)
    assert (값["A3"], 오류) == ("50", [])


def test_이름이_같은_함수를_헷갈리지_않는다(rows):
    """SUM·MIN·MAX 는 두 계산기에 똑같이 있다.

    첫 인자가 대상(지원자·채용)일 때만 집계다 — `SUM(A1,A2)` 는 칸을 더하는
    것이지 지원자를 세는 것이 아니다.
    """
    칸 = {"A1": {"글": "10"}, "A2": {"글": "20"},
         "B1": {"글": "=SUM(A1,A2)"},
         "B2": {"글": "=SUM(지원자, 저널_수)"}}
    값, 오류 = S.값들(칸, rows)
    assert 값["B1"] == "30"          # 칸을 더한 것
    assert 값["B2"] == "12"          # 2+4+0+6
    assert 오류 == []


def test_집계_안의_따옴표가_안_잘린다(rows):
    """`부서="소재분석"` 처럼 집계는 제 안에 따옴표를 품는다."""
    값, 오류 = S.값들({"A1": {"글": '=COUNT(지원자, 부서="소재분석")'}}, rows)
    assert (값["A1"], 오류) == ("2", [])


# --- 순환 참조 · 오류 --------------------------------------------------------
def test_순환_참조를_잡는다(rows):
    """안 잡으면 무한히 돈다 — 서버가 통째로 멈춘다."""
    값, 오류 = S.값들({"A1": {"글": "=B1+1"}, "B1": {"글": "=A1+1"}}, rows)
    assert 값["A1"] == "?" and 값["B1"] == "?"
    assert any("순환 참조" in x and "A1" in x and "B1" in x for x in 오류)


def test_자기를_가리켜도_잡는다(rows):
    값, 오류 = S.값들({"A1": {"글": "=A1+1"}}, rows)
    assert 값["A1"] == "?"
    assert any("순환 참조" in x for x in 오류)


def test_틀린_칸만_물음표다(rows):
    """한 칸이 틀렸다고 표가 통째로 비면 안 된다."""
    칸 = {"A1": {"글": "=1/0"}, "B1": {"글": "10"}, "C1": {"글": "=B1*2"}}
    값, 오류 = S.값들(칸, rows)
    assert 값["A1"] == "?"
    assert (값["B1"], 값["C1"]) == ("10", "20")
    assert any("0 으로 나눌" in x for x in 오류)


def test_틀린_칸을_가리키면_그_사실을_말한다(rows):
    """B1 이 "숫자가 아닙니다 '?'" 라고 하면 진짜 까닭을 못 찾는다."""
    값, 오류 = S.값들({"A1": {"글": "=1/0"}, "B1": {"글": "=A1+5"}}, rows)
    assert 값["B1"] == "?"
    assert any("B1: A1 칸을 계산하지 못했습니다" == x for x in 오류)


def test_모르는_집계_대상은_오류로(rows):
    값, 오류 = S.값들({"A1": {"글": '=COUNT(없는대상)'}}, rows)
    assert 값["A1"] == "?"
    assert any("A1:" in x for x in 오류)
