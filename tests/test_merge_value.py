"""병합한 칸은 **덮인 자리도 같은 값**이다.

`A1`·`A2` 를 합쳐 «abc» 를 적으면 격자에는 칸 하나만 그려진다. 그런데 수식에서
`=A1` 은 abc 가 나오고 `=A2` 는 빈칸이 나왔다 — 눈에 보이는 것과 가리키는 것이
어긋났다. 덮인 자리도 주인 칸을 가리키게 한다.

그리는 쪽과 계산하는 쪽이 **같은 `덮인칸`** 을 본다. 두 벌로 두면 «그려지는 칸»
과 «값이 있는 칸» 이 조용히 갈라진다.
"""

from __future__ import annotations

import pytest

from cvtool import formula as F
from cvtool import sheet as S
from cvtool.dashboards import Block, render_sheet


@pytest.fixture
def rows():
    return F.Rows(지원자=[{"부서": "가"}, {"부서": "나"}], 채용=[])


def _값(칸들, rows, **크기):
    return S.값들(칸들, rows, set(), **크기)


# --- 덮인칸 ------------------------------------------------------------------
def test_세로_병합의_덮인_자리():
    assert S.덮인칸({"A1": {"글": "abc", "세로병합": 2}}) == {"A2": "A1"}


def test_가로_병합의_덮인_자리():
    assert S.덮인칸({"A1": {"가로병합": 3}}) == {"B1": "A1", "C1": "A1"}


def test_네모_병합은_주인_말고_전부():
    덮인 = S.덮인칸({"B2": {"가로병합": 2, "세로병합": 2}})
    assert 덮인 == {"C2": "B2", "B3": "B2", "C3": "B2"}


def test_병합이_없으면_빈_묶음():
    assert S.덮인칸({"A1": {"글": "x"}, "B1": {"가로병합": 1}}) == {}


def test_격자_밖은_안_센다():
    assert S.덮인칸({"A1": {"가로병합": 5}}, 행수=10, 열수=3) == {"B1": "A1", "C1": "A1"}


# --- 값 ---------------------------------------------------------------------
def test_덮인_칸도_같은_값이다(rows):
    """신고하신 바로 그 경우."""
    칸 = {"A1": {"글": "abc", "세로병합": 2},
         "B1": {"글": "=A1"}, "B2": {"글": "=A2"}}
    값, 오류 = _값(칸, rows)
    assert 값["B1"] == 값["B2"] == "abc"
    assert not 오류


def test_가로_병합도_마찬가지다(rows):
    칸 = {"A1": {"글": "7", "가로병합": 3}, "A3": {"글": "=B1+C1"}}
    값, 오류 = _값(칸, rows)
    assert 값["A3"] == "14"
    assert not 오류


def test_주인_칸이_수식이어도_따라온다(rows):
    칸 = {"A1": {"글": "=COUNT(지원자)", "세로병합": 2}, "B2": {"글": "=A2*10"}}
    값, 오류 = _값(칸, rows)
    assert 값["A1"] == "2" and 값["B2"] == "20"
    assert not 오류


def test_병합을_풀면_다시_빈칸이다(rows):
    칸 = {"A1": {"글": "abc"}, "B2": {"글": "=A2&\"!\""}}
    값, _ = _값(칸, rows)
    assert 값["B2"] == "!"


def test_주인이_덮인_자리를_가리키면_순환_참조다(rows):
    """A1 이 A2 를 덮고 있는데 A1 에서 A2 를 부르면 자기 자신이다."""
    값, 오류 = _값({"A1": {"글": "=A2", "세로병합": 2}}, rows)
    assert 값["A1"] == "?"
    assert "순환 참조" in 오류[0]


def test_집계_조건에서도_덮인_칸이_풀린다(rows):
    칸 = {"A1": {"글": "가", "세로병합": 2},
         "B2": {"글": "=COUNTIF(부서=A2)"}}
    값, 오류 = S.값들(칸, rows, {"부서"})
    assert 값["B2"] == "1"
    assert not 오류


# --- 그리는 쪽과 같은 것을 본다 --------------------------------------------------
def test_그려지는_칸은_주인_하나뿐이다(rows):
    b = Block(id=1, dashboard_id=1, 순서=1, 종류="시트", 제목="시트",
              설정={"행수": 3, "열수": 2,
                   "시트칸": {"A1": {"글": "abc", "세로병합": 2},
                            "B2": {"글": "=A2"}}})
    결과 = render_sheet(b, rows, set())
    주소들 = [칸[0] for 줄 in 결과.행 for 칸 in 줄]
    assert "A1" in 주소들 and "A2" not in 주소들      # 덮인 자리는 안 그린다
    값 = {칸[0]: 칸[1] for 줄 in 결과.행 for 칸 in 줄}
    assert 값["B2"] == "abc"                        # 그래도 값은 있다
    assert not 결과.오류
