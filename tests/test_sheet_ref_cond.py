"""집계 조건 안에서 칸 가리키기 · 대상 생략.

`=COUNTIF(지원자, 부서=A3)` 이 **오류도 없이 0** 을 내고 있었다. `집계먼저` 가
집계 호출을 글자 그대로 `formula` 에 넘겨서, `A3` 를 칸이 아니라 «A3 라는 글자»
로 읽었다. A열에 부서를 늘어놓고 B열에서 세는 건 시트의 가장 기본 쓰임인데,
그게 조용히 0 이었다.
"""

from __future__ import annotations

import pytest

from cvtool import formula as F
from cvtool import sheet as S
from cvtool.dashboards import Block, render_table


@pytest.fixture
def rows():
    return F.Rows(
        지원자=[{"부서": "소재분석", "저널_수": "2", "한글_이름": "가", "박사_학교": "서울대"},
              {"부서": "소재분석", "저널_수": "4", "한글_이름": "나", "박사_학교": "카이스트"},
              {"부서": "공정", "저널_수": "6", "한글_이름": "다", "박사_학교": "포스텍"}],
        채용=[{"부서": "소재분석"}],
    )


아는열 = {"부서", "저널_수", "한글_이름", "박사_학교"}


def _풀기(rows, 칸: dict) -> tuple[dict, list]:
    return S.값들({k: {"글": v} for k, v in 칸.items()}, rows, 아는열)


# --- 신고받은 그것 -----------------------------------------------------------
def test_조건_값이_칸을_가리킨다(rows):
    값, 오류 = _풀기(rows, {"A3": "소재분석", "B3": "=COUNTIF(지원자, 부서=A3)"})
    assert (값["B3"], 오류) == ("2", [])


def test_대상을_안_적어도_같은_답(rows):
    값, 오류 = _풀기(rows, {"A3": "소재분석", "B3": "=COUNTIF(부서=A3)"})
    assert (값["B3"], 오류) == ("2", [])


def test_A열을_늘어놓고_B열에서_센다(rows):
    """시트의 가장 기본 쓰임. 이게 안 되면 시트를 쓸 이유가 없다."""
    값, 오류 = _풀기(rows, {
        "A1": "소재분석", "A2": "공정",
        "B1": "=COUNTIF(부서=A1)", "B2": "=COUNTIF(부서=A2)"})
    assert (값["B1"], 값["B2"]) == ("2", "1")
    assert 오류 == []


def test_가리킨_칸을_고치면_따라_바뀐다(rows):
    """A 칸을 바꿔 다시 그리면 B 가 따라와야 한다."""
    첫, _ = _풀기(rows, {"A1": "소재분석", "B1": "=COUNTIF(부서=A1)"})
    둘째, _ = _풀기(rows, {"A1": "공정", "B1": "=COUNTIF(부서=A1)"})
    assert (첫["B1"], 둘째["B1"]) == ("2", "1")


# --- 따옴표는 칸이 아니다 -------------------------------------------------------
def test_따옴표로_감싸면_그_글자를_찾는다(rows):
    """`부서="A3"` 은 A3 칸이 아니라 «A3» 라는 부서를 찾겠다는 뜻이다."""
    값, 오류 = _풀기(rows, {"A3": "소재분석", "B3": '=COUNTIF(부서="A3")'})
    assert (값["B3"], 오류) == ("0", [])


def test_열_쪽은_안_건드린다(rows):
    """열 이름이 우연히 칸 주소처럼 생겨도 칸으로 읽으면 안 된다."""
    rows2 = F.Rows(지원자=[{"A1": "값"}, {"A1": "다른값"}], 채용=[])
    값, 오류 = S.값들({"A1": {"글": "값"}, "B1": {"글": '=COUNTIF(A1="값")'}},
                  rows2, {"A1"})
    assert (값["B1"], 오류) == ("1", [])


# --- 값이 험할 때 ------------------------------------------------------------
@pytest.mark.parametrize("값", ["차세대 공정", '따옴표"있음', "쉼표,있음", "작은'따옴표"])
def test_값에_공백이나_따옴표가_있어도_안_깨진다(값):
    rows = F.Rows(지원자=[{"부서": 값}, {"부서": "다른곳"}], 채용=[])
    결과, 오류 = S.값들({"A1": {"글": 값}, "B1": {"글": "=COUNTIF(부서=A1)"}},
                   rows, {"부서"})
    assert 오류 == []
    assert 결과["B1"] == "1", f"{값!r} 에서 조건이 깨졌다"


def test_빈_칸을_가리켜도_안_터진다(rows):
    값, 오류 = _풀기(rows, {"A1": "", "B1": "=COUNTIF(부서=A1)"})
    assert (값["B1"], 오류) == ("0", [])


# --- 순환 참조 ---------------------------------------------------------------
def test_자기를_가리키는_조건도_잡는다(rows):
    """집계 안으로 숨어도 잡혀야 한다. 안 잡으면 무한히 돈다."""
    값, 오류 = _풀기(rows, {"A1": "=COUNTIF(부서=A1)"})
    assert 값["A1"] == "?"
    assert any("순환 참조" in x for x in 오류)


# --- 칸이 없는 자리는 그대로 ----------------------------------------------------
def test_숫자_축표_자유표에서는_그냥_글자다(rows):
    """거기엔 칸이 없다. `A3` 는 원래 «A3» 라는 글자다."""
    글, _값 = S.계산("=COUNTIF(부서=A3)", rows, 아는열)     # 값찾기 없음
    assert 글 == "0"
    b = Block(id=1, dashboard_id=1, 순서=1, 종류="표", 제목="",
              설정={"행": ["가"], "열": ["나"], "칸": {"가\t나": "=COUNTIF(부서=A3)"}})
    assert render_table(b, rows, {}, 아는열).행 == [("가", ["0"])]


# --- 대상 생략이 다른 함수에도 먹는다 ---------------------------------------------
@pytest.mark.parametrize("식,기대", [
    ("=AVG(저널_수)", "4.0"),
    ("=SUM(저널_수)", "12"),
    ('=LIST(한글_이름="가", 박사_학교)', "서울대"),
    ('=PCT(부서="소재분석")', "66.7%"),
    ('=COUNTIFS(부서="소재분석", 저널_수>3)', "1"),
])
def test_대상을_빼도_되는_함수들(rows, 식, 기대):
    글, _값 = S.계산(식, rows, 아는열)
    assert 글 == 기대


def test_대상을_적으면_그것을_쓴다(rows):
    """생략은 기본값일 뿐이다. 적으면 적은 대로 센다."""
    assert S.계산('=COUNT(채용, 부서="소재분석")', rows, 아는열)[0] == "1"
    assert S.계산('=COUNT(부서="소재분석")', rows, 아는열)[0] == "2"


# --- 말이 나빠지지 않았나 -------------------------------------------------------
def test_대상을_잘못_적으면_대상_이야기를_해_준다(rows):
    with pytest.raises(F.FormulaError) as exc:
        S.계산("=COUNT(없는대상)", rows, 아는열)
    말 = str(exc.value)
    assert "없는대상" in 말 and "지원자" in 말 and "채용" in 말


def test_칸을_셈하는_함수는_여전히_칸을_센다(rows):
    """`=SUM(A1:A3)` 이 «지원자의 A1:A3 열» 로 읽히면 안 된다."""
    값, 오류 = _풀기(rows, {"A1": "1", "A2": "2", "A3": "3",
                        "B1": "=SUM(A1:A3)", "B2": "=COUNT(A1,A2)",
                        "B3": "=AVERAGE(A1:A3)"})
    assert (값["B1"], 값["B2"], 값["B3"]) == ("6", "2", "2")
    assert 오류 == []


# --- 화면에서만 드러난 것들 ------------------------------------------------------
def test_수식칸의_Enter_를_우리가_잡는다():
    """안 잡으면 브라우저가 제 나름대로 폼을 보낸다.

    그게 `change` 보다 먼저 나가는 때가 있어서, 방금 친 글이 안 담긴 옛 값이
    저장된다 — 같은 순서로 쳐도 어떤 칸은 저장되고 어떤 칸은 조용히 사라졌다.
    자동완성 목록이 열려 있을 때는 비켜 준다 (그때 Enter 는 «고른다» 는 뜻).
    """
    from cvtool.web.app import _SHEET_JS

    assert "function 글넣기()" in _SHEET_JS
    assert "수식칸.addEventListener('change', 글넣기)" in _SHEET_JS
    assert "e.key !== 'Enter' || document.getElementById('fxdrop')" in _SHEET_JS
    assert "e.preventDefault()" in _SHEET_JS


def test_숫자만_친_것은_자동완성하지_않는다():
    """`1` 을 치고 Enter 를 누르면 `1저자_우수_제출처` 가 들어가 버렸다.

    칸에 숫자를 적는 건 흔한 일이라, 숫자로만 된 낱말은 완성 대상이 아니다.
    """
    from cvtool.web.app import _FXAC_JS

    assert "if(/^[0-9.]+$/.test(말)) return [];" in _FXAC_JS
    assert "if(!말) return [];" in _FXAC_JS          # 빈 칸에도 안 뜬다
